import type { OpenAPIObject } from '@nestjs/swagger';
import { ERROR_ENVELOPE_SCHEMA } from './envelope-transform.js';

/**
 * Rules that the generated OpenAPI document must satisfy.
 *
 * The skill `researchos-api-endpoint` describes these rules in prose, but
 * prose does not fail a build. This module turns them into checks that run
 * in `openapi-rules.spec.ts`, so a route that forgets its `@ApiOperation`
 * summary, a DTO field without a description, or an error response that
 * declares its own body type is caught by `pnpm --filter api test` instead
 * of by a reviewer reading the diff.
 *
 * The rules run against the **transformed** document — the one produced by
 * `applyEnvelopeTransform` — because that is the document the frontend
 * client is generated from.
 */

/** HTTP methods that can appear as keys of a path item object. */
const HTTP_METHODS = [
  'get',
  'put',
  'post',
  'delete',
  'options',
  'head',
  'patch',
  'trace',
] as const;

/**
 * Component names that must never exist in the document.
 *
 * A component named `String` generates `models/string.ts` containing
 * `export type String = string`, and the models barrel re-exports it with
 * `export * from './string'`, which shadows the global `String` type in
 * every file that imports the barrel. The same trap applies to `Number` and
 * `Boolean`.
 */
const FORBIDDEN_COMPONENT_NAMES = ['String', 'Number', 'Boolean'] as const;

/**
 * Field names reserved for the response envelope.
 *
 * The frontend mutator decides whether a body is an envelope by checking
 * that it has both `success` and `data` and that `success` is a boolean. A
 * business DTO with both fields would be unwrapped one level too far.
 */
const RESERVED_FIELD_NAMES = ['success', 'data'] as const;

/** A single broken rule. */
export interface OpenApiViolation {
  /** Stable identifier of the rule, e.g. `operation.summary`. */
  rule: string;
  /** Where the violation lives, e.g. `GET /profiles/{id}`. */
  location: string;
  /** What is wrong, in one sentence. */
  message: string;
}

/** The loose shape of the parts of the document this module inspects. */
type JsonSchema = Record<string, any>;

function isNonEmptyString(value: unknown): value is string {
  return typeof value === 'string' && value.trim().length > 0;
}

/**
 * Returns true for the schemas that are generated by the envelope transform
 * rather than declared by a developer.
 *
 * Their properties are not described by hand, so the "every property needs a
 * description" rule does not apply to them. The payload schema they wrap is
 * still checked, because that one is declared by a developer.
 */
function isGeneratedSchema(name: string): boolean {
  return name === ERROR_ENVELOPE_SCHEMA || name.endsWith('Envelope');
}

/**
 * Checks every rule against a document.
 *
 * Returns the violations in the order they were found. An empty array means
 * the document satisfies every rule.
 */
export function checkOpenApiDocument(
  document: OpenAPIObject,
): OpenApiViolation[] {
  const violations: OpenApiViolation[] = [];
  const doc = document as unknown as JsonSchema;
  const schemas: JsonSchema = doc.components?.schemas ?? {};

  checkForbiddenComponentNames(schemas, violations);

  for (const [path, pathItem] of Object.entries<JsonSchema>(doc.paths ?? {})) {
    for (const method of HTTP_METHODS) {
      const operation = pathItem?.[method];

      if (!operation) {
        continue;
      }

      const location = `${method.toUpperCase()} ${path}`;
      checkOperationSummary(operation, location, violations);
      checkResponses(operation, location, schemas, violations);
      checkParameters(operation, location, violations);
      checkRequestBody(operation, location, schemas, violations);
    }
  }

  for (const [name, schema] of Object.entries<JsonSchema>(schemas)) {
    checkSchemaProperties(name, schema, schemas, violations);
    checkReservedFieldNames(name, schema, violations);
  }

  return violations;
}

/**
 * A component named `String`, `Number` or `Boolean` shadows a global type in
 * the generated frontend models barrel.
 */
function checkForbiddenComponentNames(
  schemas: JsonSchema,
  violations: OpenApiViolation[],
): void {
  for (const name of FORBIDDEN_COMPONENT_NAMES) {
    if (schemas[name]) {
      violations.push({
        rule: 'component.name',
        location: `components.schemas.${name}`,
        message:
          `A component named "${name}" shadows the global type of the same ` +
          `name in the generated models barrel. Keep primitive payloads inline.`,
      });
    }
  }
}

/** Every route must have a non-empty summary: it is the route's description. */
function checkOperationSummary(
  operation: JsonSchema,
  location: string,
  violations: OpenApiViolation[],
): void {
  if (!isNonEmptyString(operation.summary)) {
    violations.push({
      rule: 'operation.summary',
      location,
      message:
        'The route has no @ApiOperation summary. Every route needs a ' +
        'non-empty summary; it is what Swagger UI shows and what the ' +
        'generated client copies into its JSDoc.',
    });
  }
}

/**
 * Every declared response needs a description, and the route needs at least
 * one response.
 *
 * A response with an empty description is what NestJS generates when a
 * route declares no `@Api*Response` at all, so this rule is really the
 * "declare your responses" rule.
 */
function checkResponses(
  operation: JsonSchema,
  location: string,
  schemas: JsonSchema,
  violations: OpenApiViolation[],
): void {
  const responses: JsonSchema = operation.responses ?? {};
  const statuses = Object.keys(responses);

  if (statuses.length === 0) {
    violations.push({
      rule: 'operation.responses',
      location,
      message:
        'The route declares no response. Add at least one @Api*Response ' +
        'decorator with an explicit type.',
    });

    return;
  }

  for (const [status, response] of Object.entries<JsonSchema>(responses)) {
    if (!isNonEmptyString(response.description)) {
      violations.push({
        rule: 'response.description',
        location: `${location} -> ${status}`,
        message:
          'The response has no description. Add one to the @Api*Response ' +
          'decorator; it labels the status code in the Swagger responses table.',
      });
    }

    if (/^[45]\d\d$/.test(status)) {
      checkErrorResponseSchema(response, location, status, schemas, violations);
    }
  }
}

/**
 * An error response must describe the shared error envelope.
 *
 * The server always answers a failure with `ApiErrorResponseDto` — the
 * exception filter is global and knows nothing about the route. An error
 * response that declares its own `type` describes a body the server never
 * sends, so the generated client and the runtime disagree.
 */
function checkErrorResponseSchema(
  response: JsonSchema,
  location: string,
  status: string,
  schemas: JsonSchema,
  violations: OpenApiViolation[],
): void {
  const schema = response.content?.['application/json']?.schema;

  if (!schema) {
    violations.push({
      rule: 'errorResponse.schema',
      location: `${location} -> ${status}`,
      message:
        `The error response has no body. The server always answers a ` +
        `failure with the shared error envelope, so the response must ` +
        `point at "${ERROR_ENVELOPE_SCHEMA}".`,
    });

    return;
  }

  const expected = `#/components/schemas/${ERROR_ENVELOPE_SCHEMA}`;

  if (schema.$ref !== expected) {
    violations.push({
      rule: 'errorResponse.schema',
      location: `${location} -> ${status}`,
      message:
        `The error response declares its own body type instead of the ` +
        `shared error envelope. Do not pass "type" to an error ` +
        `@Api*Response decorator; the server always sends ` +
        `"${ERROR_ENVELOPE_SCHEMA}".`,
    });
  }
}

/** Every parameter needs a description: it is what a reader sees in Swagger. */
function checkParameters(
  operation: JsonSchema,
  location: string,
  violations: OpenApiViolation[],
): void {
  for (const parameter of operation.parameters ?? []) {
    if (!isNonEmptyString(parameter.description)) {
      violations.push({
        rule: 'parameter.description',
        location: `${location} -> ${parameter.in ?? 'parameter'} ${parameter.name}`,
        message:
          `The parameter "${parameter.name}" has no description. Path and ` +
          `header parameters need an explicit @ApiParam or @ApiHeader; ` +
          `query parameters inherit theirs from the DTO's @ApiProperty.`,
      });
    }
  }
}

/**
 * Every property of a request body needs a description.
 *
 * The body schema is usually a `$ref` to a DTO, in which case the DTO's own
 * properties are checked when the components are walked. An inline body is
 * checked here.
 */
function checkRequestBody(
  operation: JsonSchema,
  location: string,
  schemas: JsonSchema,
  violations: OpenApiViolation[],
): void {
  const schema = operation.requestBody?.content?.['application/json']?.schema;

  if (!schema) {
    return;
  }

  const resolved = resolveSchema(schema, schemas);

  if (!resolved) {
    return;
  }

  for (const [name, property] of Object.entries<JsonSchema>(
    resolved.properties ?? {},
  )) {
    if (!isNonEmptyString(property.description)) {
      violations.push({
        rule: 'bodyProperty.description',
        location: `${location} -> body.${name}`,
        message:
          `The request body property "${name}" has no description. Add one ` +
          `to its @ApiProperty decorator.`,
      });
    }
  }
}

/**
 * Every property of a developer-declared schema needs a description.
 *
 * The generated envelope schemas are skipped: they are produced by the
 * transform, not written by hand.
 */
function checkSchemaProperties(
  name: string,
  schema: JsonSchema,
  schemas: JsonSchema,
  violations: OpenApiViolation[],
): void {
  if (isGeneratedSchema(name)) {
    return;
  }

  for (const [propertyName, property] of Object.entries<JsonSchema>(
    schema.properties ?? {},
  )) {
    if (!isNonEmptyString(property.description)) {
      violations.push({
        rule: 'schemaProperty.description',
        location: `components.schemas.${name}.${propertyName}`,
        message:
          `The property "${propertyName}" has no description. Add one to ` +
          `its @ApiProperty decorator; it is the only place a reader learns ` +
          `what the field means.`,
      });
    }
  }
}

/**
 * A business DTO must not use both reserved envelope field names.
 *
 * `success` and `data` together make the frontend mutator treat the
 * payload as an envelope and unwrap it one level too far.
 */
function checkReservedFieldNames(
  name: string,
  schema: JsonSchema,
  violations: OpenApiViolation[],
): void {
  if (isGeneratedSchema(name)) {
    return;
  }

  const properties = Object.keys(schema.properties ?? {});
  const used = RESERVED_FIELD_NAMES.filter((field) =>
    properties.includes(field),
  );

  if (used.length === RESERVED_FIELD_NAMES.length) {
    violations.push({
      rule: 'schema.reservedFields',
      location: `components.schemas.${name}`,
      message:
        `The DTO declares "${used.join('" and "')}", which are reserved for ` +
        `the response envelope. The frontend would unwrap the payload one ` +
        `level too far. Rename one of them.`,
    });
  }
}

/**
 * Resolves a schema reference to the schema it points at.
 *
 * Returns `undefined` for a reference that cannot be resolved, which happens
 * only for a malformed document.
 */
function resolveSchema(
  schema: JsonSchema,
  schemas: JsonSchema,
): JsonSchema | undefined {
  const ref = schema?.$ref;

  if (typeof ref !== 'string') {
    return schema;
  }

  const name = ref.split('/').pop();

  return name ? schemas[name] : undefined;
}
