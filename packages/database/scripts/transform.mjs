/**
 * Rewrites an introspected Prisma schema into the conventions of this
 * repository.
 *
 * `prisma db pull` names every model after its SQL table and every field
 * after its SQL column, and it does not write any `@map` or `@@map`
 * attribute. The repository convention is the opposite: PascalCase models
 * and enums, camelCase fields, and explicit `@map` / `@@map` attributes
 * pointing at the snake_case names that live in SQL.
 *
 * The transformation is pure text in, pure text out. It never talks to a
 * database, so the drift check and the schema generator can share it and
 * still be guaranteed to produce identical results.
 */

/** Converts a snake_case SQL name into a camelCase Prisma field name. */
export function toCamelCase(value) {
  return value.replace(/_([a-z0-9])/g, (_, character) => character.toUpperCase());
}

/** Converts a snake_case SQL name into a PascalCase Prisma identifier. */
export function toPascalCase(value) {
  const camel = toCamelCase(value);
  return camel.charAt(0).toUpperCase() + camel.slice(1);
}

/**
 * Splits the schema into its top level blocks.
 *
 * Each block is `{ kind, name, header, lines }` where `lines` are the body
 * lines with the original indentation preserved.
 */
function parseBlocks(schema) {
  const blocks = [];
  const lines = schema.split(/\r?\n/);

  let current = null;

  for (const line of lines) {
    const header = /^(\w+)\s+(\w+)\s*\{$/.exec(line.trim());

    if (header) {
      current = {
        kind: header[1],
        name: header[2],
        header: line.trim(),
        lines: [],
      };
      blocks.push(current);
      continue;
    }

    if (line.trim() === '}') {
      current = null;
      continue;
    }

    if (current) {
      current.lines.push(line);
    }
  }

  return blocks;
}

/**
 * Returns the type of a field.
 *
 * `user_id  String  @db.Uuid` has the type `String`.
 * `digest_items  digest_items[]  @relation(...)` has the type `digest_items`.
 */
function fieldType(line) {
  const match = /^\s+(\w+)\s+((?:[A-Za-z_][A-Za-z0-9_]*)(?:\[\])?\??)/.exec(line);

  if (!match) return undefined;

  return match[2];
}

/**
 * Parses a field line into its indent, name, type and the attributes that
 * follow the type.
 *
 * The type keeps its optional marker, because `String?` and `String` are
 * different types. The attributes are returned without the type, so that the
 * caller can write the type back itself.
 *
 * A line that is not a field returns undefined.
 */
function parseField(line) {
  const match =
    /^(\s+)(\w+)(\s+)([A-Za-z_][A-Za-z0-9_]*)(\[\])?(\?)?(\s.*)?$/.exec(line);

  if (!match) return undefined;

  const [, indent, name, , baseType, list, optional, rest = ''] = match;

  return {
    indent,
    name,
    rest,
    type: `${baseType}${list ?? ''}${optional ?? ''}`,
    baseType,
    isList: Boolean(list),
    isOptional: Boolean(optional),
  };
}

/**
 * The header that is placed at the top of the generated schema.
 *
 * It is written by the generator, not by hand, so that it survives every
 * regeneration.
 */
const header = `// ResearchOS Prisma datamodel.
//
// DO NOT EDIT THIS FILE BY HAND.
//
// The database schema is owned by \`ResearchOS.sql\` at the root of the
// workspace. This file is a generated artifact: it is produced by
// introspecting the live database and rewriting the result into the
// conventions of this repository (PascalCase models, camelCase fields, and
// explicit \`@map\` / \`@@map\` attributes pointing at the snake_case names in
// SQL).
//
// To change the schema:
//   1. Edit \`ResearchOS.sql\`.
//   2. Run \`pnpm --filter @researchos/database db:reset\` to rebuild the
//      database and regenerate this file.
//   3. Run \`pnpm --filter @researchos/database db:drift\` to confirm that
//      this file still matches the SQL.
//
// Prisma Migrate is deliberately not used. The schema contains CHECK
// constraints, DEFERRABLE foreign keys, expression indexes, partial unique
// indexes, views and triggers that the Prisma schema language cannot
// represent. Prisma Migrate's differ is blind to those objects: it neither
// manages nor validates them, and a migration it generates would not
// reproduce the database. The SQL stays the only source of truth.
`;

/**
 * Rewrites an introspected schema into the repository conventions.
 *
 * @param {string} introspected The output of `prisma db pull`.
 * @returns {string} The rewritten schema.
 */
export function transformSchema(introspected) {
  const blocks = parseBlocks(introspected);

  const modelBlocks = blocks.filter((block) => block.kind === 'model');
  const enumBlocks = blocks.filter((block) => block.kind === 'enum');

  const modelNames = new Set(modelBlocks.map((block) => block.name));
  const enumNames = new Set(enumBlocks.map((block) => block.name));

  // The rename maps. The original names stay in SQL and are recorded through
  // `@@map` on the model and through `@map` on the scalar fields.
  const modelRename = new Map(
    modelBlocks.map((block) => [block.name, toPascalCase(block.name)]),
  );
  const enumRename = new Map(
    enumBlocks.map((block) => [block.name, toPascalCase(block.name)]),
  );

  // Per model, the map from the original field name to the renamed one. The
  // relation attributes and the block attributes both need it.
  const fieldRenames = new Map();

  for (const block of modelBlocks) {
    const renames = new Map();

    for (const line of block.lines) {
      if (line.trim().startsWith('@@')) continue;

      const field = parseField(line);
      if (!field) continue;

      const camel = toCamelCase(field.name);

      if (renames.has(field.name) && renames.get(field.name) !== camel) {
        throw new Error(
          `Renaming "${field.name}" to "${camel}" collides with another field in model "${block.name}".`,
        );
      }

      renames.set(field.name, camel);
    }

    // Two different columns must not collapse onto the same camelCase name.
    const seen = new Map();

    for (const [original, camel] of renames) {
      if (seen.has(camel)) {
        throw new Error(
          `Columns "${seen.get(camel)}" and "${original}" of model "${block.name}" both map to "${camel}".`,
        );
      }

      seen.set(camel, original);
    }

    fieldRenames.set(block.name, renames);
  }

  const output = [];

  for (const block of blocks) {
    if (block.kind === 'generator' || block.kind === 'datasource') {
      output.push(block.header);
      output.push(...block.lines);
      output.push('}');
      output.push('');
      continue;
    }

    if (block.kind === 'enum') {
      const renamed = enumRename.get(block.name);

      output.push(`enum ${renamed} {`);

      for (const line of block.lines) {
        output.push(line);
      }

      output.push(`  @@map("${block.name}")`);
      output.push('}');
      output.push('');
      continue;
    }

    if (block.kind === 'model') {
      const renamed = modelRename.get(block.name);
      const renames = fieldRenames.get(block.name);

      output.push(`model ${renamed} {`);

      for (const line of block.lines) {
        if (line.trim().startsWith('@@')) {
          output.push(rewriteBlockAttribute(line, renames));
          continue;
        }

        const field = parseField(line);

        if (!field) {
          output.push(line);
          continue;
        }

        const isRelation =
          field.baseType !== undefined && modelNames.has(field.baseType);
        const camel = toCamelCase(field.name);

        // A relation type is a model name, an enum type is an enum name, and
        // a scalar type stays as it is.
        const newBaseType =
          field.baseType === undefined
            ? undefined
            : (modelRename.get(field.baseType) ??
              enumRename.get(field.baseType) ??
              field.baseType);

        const newType = `${newBaseType ?? field.baseType}${field.isList ? '[]' : ''}${field.isOptional ? '?' : ''}`;

        if (isRelation) {
          // A relation field has no column of its own, so it never gets an
          // `@map`. Its attributes refer to the renamed fields.
          const rest = rewriteRelationAttributes(
            field.rest,
            renames,
            fieldRenames.get(field.baseType),
          );

          output.push(`${field.indent}${camel} ${newType}${rest}`);
          continue;
        }

        // A scalar field keeps a pointer to its column. The `@map` is only
        // needed when the name actually changed, and it is never written
        // twice.
        const rest = field.rest.includes('@map(')
          ? field.rest
          : camel === field.name
            ? field.rest
            : `${field.rest} @map("${field.name}")`;

        output.push(`${field.indent}${camel} ${newType}${rest}`);      }

      output.push(`  @@map("${block.name}")`);
      output.push('}');
      output.push('');
      continue;
    }
  }

  return `${header}\n${output.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}

/**
 * Rewrites the field names inside a block attribute such as
 * `@@unique([user_id, period_start])`.
 */
function rewriteBlockAttribute(line, renames) {
  return line.replace(/\[\s*([^\]]*)\]/g, (match, inner) => {
    if (!inner.trim()) return match;

    const rewritten = inner
      .split(',')
      .map((entry) => {
        const trimmed = entry.trim();
        return renames.get(trimmed) ?? trimmed;
      })
      .join(', ');

    return `[${rewritten}]`;
  });
}

/**
 * Rewrites the `fields` and `references` lists inside a `@relation`
 * attribute.
 *
 * `fields` refers to the fields of the current model, `references` refers to
 * the fields of the model on the other side of the relation. Both have to use
 * the new field names.
 */
function rewriteRelationAttributes(rest, renames, referencedRenames) {
  return rest.replace(
    /(fields|references)\s*:\s*\[([^\]]*)\]/g,
    (match, keyword, inner) => {
      const source = keyword === 'fields' ? renames : referencedRenames;

      if (!source) return match;

      const rewritten = inner
        .split(',')
        .map((entry) => {
          const trimmed = entry.trim();
          return source.get(trimmed) ?? trimmed;
        })
        .join(', ');

      return `${keyword}: [${rewritten}]`;
    },
  );
}