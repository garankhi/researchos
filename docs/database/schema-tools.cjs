// Use the official editor diagnostics AND v2 parser; CLI export alone misses
// RefColumnMismatch diagnostics and its legacy parser rejects optional operators.
// Run via build-schema.ps1 or:
// pnpm --package=@dbml/cli@11.0.0 dlx -c "node docs/database/schema-tools.cjs --check"
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { createRequire } = require('node:module');

const cliPackage = (process.env.PATH || '').split(path.delimiter)
  .map(bin => path.resolve(bin, '..', '@dbml', 'cli', 'package.json'))
  .find(candidate => fs.existsSync(candidate));
if (!cliPackage) throw new Error('Run using the pinned pnpm --package=@dbml/cli@11.0.0 dlx command.');
const cliRequire = createRequire(fs.realpathSync(cliPackage));
const { Parser, ModelExporter } = cliRequire('@dbml/core');
const coreRequire = createRequire(cliRequire.resolve('@dbml/core'));
const { Compiler, MemoryProjectLayout, DEFAULT_ENTRY } = coreRequire('@dbml/parse');

function diagnostics(source) {
  const layout = new MemoryProjectLayout();
  layout.setSource(DEFAULT_ENTRY, source);
  return new Compiler(layout).initMonacoServices().diagnosticsProvider.provideDiagnostics(DEFAULT_ENTRY);
}

// Regression seam: the same editor provider that reports the user's symptom.
const fixture = 'Table parents {\n id int [pk]\n}\nTable children {\n parent_id int\n}\nRef: children.parent_id > parents.id';
assert(diagnostics(fixture).some(d => d.text.includes('nullable but operator')));
assert.equal(diagnostics(fixture.replace(' > ', ' >? ')).length, 0);
const composite = 'Table parents {\n a int [not null]\n b int [not null]\n indexes { (a,b) [pk] }\n}\nTable children {\n a int\n b int\n}\nRef: children.(a,b) > parents.(a,b)';
assert(diagnostics(composite).some(d => d.text.includes('all nullable')));
assert.equal(diagnostics(composite.replace(' > ', ' >? ')).length, 0);

const source = fs.readFileSync(path.join(__dirname, 'ResearchOS.dbml'), 'utf8');
const issues = diagnostics(source);
if (issues.length) {
  for (const issue of issues) console.error(`${issue.startRow}:${issue.startColumn} [${issue.type}] ${issue.text}`);
  throw new Error(`DBML editor diagnostics: ${issues.length}. Build stopped.`);
}
const model = Parser.parse(source, 'dbmlv2');
console.log('PASS: official editor diagnostics = 0; nullable FK regression fixtures passed; v2 parser passed.');
if (!process.argv.includes('--check')) {
  const output = process.env.RESEARCHOS_SCHEMA_OUTPUT || path.join(__dirname, 'ResearchOS.sql');
  const header = '-- ResearchOS v4.3. Generated by build-schema.ps1; fresh database only.\nBEGIN;\nCREATE EXTENSION IF NOT EXISTS pg_trgm;\n';
  const sql = ModelExporter.export(model, 'postgres');
  const features = fs.readFileSync(path.join(__dirname, 'postgres-features.sql'), 'utf8');
  fs.writeFileSync(output, header + sql + '\n' + features + '\nCOMMIT;\n', 'utf8');
  console.log(`Built ${output}`);
}
